<?php
function saveProductImage(array $file): string {
    if (($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK) {
        throw new InvalidArgumentException('Upload gagal. Pilih gambar maksimal 2 MB.');
    }
    $tmp = $file['tmp_name'] ?? '';
    if (!is_string($tmp) || !is_uploaded_file($tmp)) {
        throw new InvalidArgumentException('Sumber upload tidak valid.');
    }
    if (filesize($tmp) > 2 * 1024 * 1024 || filesize($tmp) < 1) {
        throw new InvalidArgumentException('Ukuran gambar maksimal 2 MB.');
    }
    $mime = (new finfo(FILEINFO_MIME_TYPE))->file($tmp);
    $extensions = ['image/jpeg' => 'jpg', 'image/png' => 'png', 'image/webp' => 'webp'];
    $info = @getimagesize($tmp);
    if (
        !isset($extensions[$mime]) ||
        !$info ||
        ($info['mime'] ?? '') !== $mime ||
        $info[0] > 8000 ||
        $info[1] > 8000
    ) {
        throw new InvalidArgumentException(
            'Gunakan gambar JPG, PNG, atau WebP yang valid (maksimal 8000 × 8000).'
        );
    }
    $dir = __DIR__ . '/../uploads/products';
    if (!is_dir($dir) && !mkdir($dir, 0755, true)) {
        throw new RuntimeException('Direktori upload tidak tersedia.');
    }
    $name = bin2hex(random_bytes(20)) . '.' . $extensions[$mime];
    if (!move_uploaded_file($tmp, $dir . '/' . $name)) {
        throw new RuntimeException('Gambar belum dapat disimpan. Periksa izin direktori upload.');
    }
    chmod($dir . '/' . $name, 0644);
    return $name;
}

function removeProductImage(?string $name): void {
    // Only remove files generated by this helper, never a user-controlled path.
    if ($name && preg_match('/^[a-f0-9]{40}\.(jpg|png|webp)$/D', $name)) {
        $p = __DIR__ . '/../uploads/products/' . $name;
        if (is_file($p)) {
            unlink($p);
        }
    }
}
